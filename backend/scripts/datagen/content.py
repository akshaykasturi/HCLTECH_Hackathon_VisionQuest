"""Scenario content for the synthetic ITSM dataset (100% synthetic, no real systems or people).

One FAMILY per KB article (KB-001 .. KB-022). Each family has 5 SCENARIOS: distinct root causes with their own
symptoms, error signal, diagnostic check and fix steps. build.py assigns whole scenarios to one split
(3 train, 1 val, 1 test per family), so no scenario template appears in two splits.

Scenario fields: key, subjects, descriptions, sparse (vague wording, used for CLARIFY cases), cause, signal
(error code or log signal), diag (diagnostic check sentence for the KB), steps (fix steps, copied into tickets
and the KB), prio (typical priority), fix (index of the step that is the key fix; its sentence is the gold
key_sentence).
"""
from dataclasses import dataclass, field


